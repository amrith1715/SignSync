"""
math_utils.py
-------------
Mathematical preprocessing functions for hand landmarks.

NORMALIZATION PIPELINE
──────────────────────────
MediaPipe RAW landmarks have two learning problems:

1. Position dependency: If you place your hand in the left corner or
in the center, the coordinates are different even though the sign is the same.

2. Scale dependency: If you place your hand near or far from the camera,
the coordinates are different even though the sign is the same.

We solve both with two sequential mathematical steps:

Step 1 — Spatial normalization (translation to the origin):
p'_i = p_i - p_0 ∀i ∈ {0..20}

where p_0 is the wrist (landmark 0, Wrist).

Result: the wrist is located at (0, 0, 0).

Step 2 — Scale Normalization (Division by Palm Length):

p''_i = p'_i / d ∀i ∈ {0..20}

where d = ‖p'_9 - p'_0‖₂ = ‖p'_9‖₂

p'_9 is the MCP of the middle finger (landmark 9).

This distance represents the "size" of the palm and is stable
regardless of the distance to the camera.

Result: the palm vector has a norm of 1.

After these two steps, the same sign made in any position and at any distance produces (approximately) the same vector of 63 features.

Public functions:

normalize_landmarks(array) — normalize an array (21, 3) 
normalize_flat(flat_vector) — normalizes a vector (63,) 
load_raw_csv(path) — load the raw CSV → X (N,63), y (N,) 
load_processed_csv(path) — load the processed CSV → X (N,63), y (N,) 
save_processed_csv(X, y, path) — saves normalized X and y to CSV 
preprocess_csv(raw, processed) — complete pipeline raw → processed
"""

import numpy as np
import pandas as pd
from pathlib import Path
from typing import Tuple

# Landmark constants
WRIST_IDX       = 0   # Wrist — origin of translation
PALM_REF_IDX    = 9   # Heart MCP — scale reference
NUM_LANDMARKS   = 21
FEATURE_SIZE    = NUM_LANDMARKS * 3  # 63
RAW_LANDMARK_COLS = [
    f"{axis}{i}"
    for i in range(NUM_LANDMARKS)
    for axis in ("x", "y", "z")
]


# Mathematical core

def normalize_landmarks(landmarks: np.ndarray) -> np.ndarray:
    """
    Applies spatial and scale normalization to an array of landmarks.

    Step 1 — Translation to the origin:
    Subtracts the wrist position (landmark 0) from all points.
    Makes the vector invariant with respect to the hand's position in the frame.

    Step 2 — Scale normalization:
    Divides all points by the Euclidean distance between the wrist
    and the middle finger's MCP (landmark 9).
    Makes the vector invariant with respect to the distance from the hand to the camera.

    Args:
    landmarks: Array of shape (21, 3) with coordinates [x, y, z]
    in MediaPipe space (x, y ∈ [0, 1], z relative).

    Returns:
    Normalized array of shape (21, 3). The wrist is (0, 0, 0) and the
    distance wrist→MCP_heart is 1.0.

    Raises:
    ValueError: If the hand is too small (d < 1e-6), which

    would indicate corrupt landmarks or out-of-frame manipulation.
    """
    landmarks = landmarks.astype(np.float64)

    # Step 1: Translation — wrist to origin
    wrist = landmarks[WRIST_IDX].copy()      # p_0
    translated = landmarks - wrist           # p'_i = p_i - p_0

    # Step 2: Scale — divide by palm length
    # d = ‖p'_9‖₂  (Euclidean norm of the vector wrist→MCP_heart)
    palm_vec = translated[PALM_REF_IDX]    
    d = np.linalg.norm(palm_vec)

    if d < 1e-6:
        raise ValueError(
            f"Palm distance too small (d={d:.2e}). "
            "Check that the hand is fully visible in the frame."
        )

    normalized = translated / d              # p''_i = p'_i / d

    return normalized.astype(np.float32)


def normalize_flat(flat_vector: np.ndarray) -> np.ndarray:
    """
    A version of normalize_landmarks for flat vectors with 63 features.

    Useful in real-time inference, where process_frame returns
    HandLandmarks.flat directly.

    Args:

    flat_vector: A flat (63) shape array with order [x0,y0,z0,...,x20,y20,z20].

    Returns:

    A normalized (63) shape array.
    """
    if flat_vector.shape != (FEATURE_SIZE,):
        raise ValueError(
            f"Se esperaba un vector de {FEATURE_SIZE} elementos, "
            f"se recibió {flat_vector.shape}."
        )
    landmarks_2d = flat_vector.reshape(NUM_LANDMARKS, 3)
    return normalize_landmarks(landmarks_2d).flatten()

# I/O data
def load_raw_csv(path: Path) -> Tuple[np.ndarray, np.ndarray]:
    df = pd.read_csv(path)
    y  = np.array(df["label"].values, dtype=str)
    X  = np.array(df[RAW_LANDMARK_COLS].values, dtype=np.float32)
    return X, y


def load_processed_csv(path: Path) -> Tuple[np.ndarray, np.ndarray]:
    """
    Load the processed (normalized) CSV file generated by `save_processed_csv`.

    Args:
    path: Path to the processed CSV file (e.g., data/processed/landmarks_norm.csv).

    Returns:
    (X, y):
    X — a normalized (N, 63) array of floats.
    y — an array of (N,) strings containing the letter labels.
    """
    return load_raw_csv(path) 


def save_processed_csv(
    X: np.ndarray,
    y: np.ndarray,
    path: Path,
) -> None:
    """
    Saves the normalized data to a CSV file in the same format as the raw data.

    Args:
    X: Array of float32 in shape (N, 63) — normalized data.
    Y: Array of shape (N,) — letter labels.

    Path: Output path (e.g., data/processed/landmarks_norm.csv).
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    df = pd.DataFrame(X, columns=RAW_LANDMARK_COLS)
    df.insert(0, "label", y)
    df.to_csv(path, index=False)
    print(f"[math_utils] CSV procesado guardado en: {path.resolve()}")
    print(f"[math_utils] Forma: {X.shape}  |  Clases: {sorted(set(y))}")


# Complete pipeline
def preprocess_csv(
    raw_path: Path,
    processed_path: Path,
    verbose: bool = True,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Complete pipeline: loads the raw CSV, normalizes it, and saves the processed CSV.

    Applies normalize_landmarks row by row. Rows with corrupt landmarks (palm distance < 1e-6) are discarded with a warning.

    Args:
    raw_path: Path to the raw CSV.
    processed_path: Output path of the processed CSV.
    verbose: If True, prints process statistics.

    Returns:
    (X_norm, y):
    X_norm — normalized float32 array (N, 63).
    y — array (N,) of corresponding tags.
    """
    X_raw, y = load_raw_csv(raw_path)

    if verbose:
        print(f"[math_utils] Cargadas {len(X_raw)} muestras de '{raw_path}'.")
        _print_class_counts(y, "Distribución raw")

    X_norm_list = []
    y_clean_list = []
    n_dropped = 0

    for i, (row, label) in enumerate(zip(X_raw, y)):
        try:
            landmarks_2d = row.reshape(NUM_LANDMARKS, 3)
            norm_flat    = normalize_landmarks(landmarks_2d).flatten()
            X_norm_list.append(norm_flat)
            y_clean_list.append(label)
        except ValueError as e:
            if verbose:
                print(f"  [!] Row {i} discarded ({label}): {e}")
            n_dropped += 1

    X_norm = np.array(X_norm_list, dtype=np.float32)
    y_clean = np.array(y_clean_list)

    if verbose and n_dropped > 0:
        print(f"[math_utils] {n_dropped} rows discarded by corrupt landmarks.")

    save_processed_csv(X_norm, y_clean, processed_path)

    if verbose:
        _print_normalization_stats(X_raw, X_norm)

    return X_norm, y_clean


# Intern utilities
def _print_class_counts(y: np.ndarray, title: str = "") -> None:
    """Imprime el número de muestras por clase."""
    unique, counts = np.unique(y, return_counts=True)
    if title:
        print(f"  {title}:")
    for label, count in zip(unique, counts):
        print(f"    {label}: {count}")


def _print_normalization_stats(X_raw: np.ndarray, X_norm: np.ndarray) -> None:
    """Print before/after statistics to verify normalization."""
    print("\n[math_utils] Standardization verification:")
    print(f"  Rango raw  → x: [{X_raw[:, 0::3].min():.3f}, {X_raw[:, 0::3].max():.3f}]"
          f"  y: [{X_raw[:, 1::3].min():.3f}, {X_raw[:, 1::3].max():.3f}]")
    print(f"  Rango norm → x: [{X_norm[:, 0::3].min():.3f}, {X_norm[:, 0::3].max():.3f}]"
          f"  y: [{X_norm[:, 1::3].min():.3f}, {X_norm[:, 1::3].max():.3f}]")

    # Verify that the normalized wrist is (0,0,0)
    wrist_norm = X_norm[:, :3]   # columns x0, y0, z0
    wrist_max  = np.abs(wrist_norm).max()
    print(f"  Wrist after normalization (should be ≈0): max abs = {wrist_max:.2e}")

    # Verify that the wrist→MCP_heart distance is ≈1
    palm_vecs = X_norm[:, PALM_REF_IDX*3 : PALM_REF_IDX*3 + 3]  # x9,y9,z9
    palm_norms = np.linalg.norm(palm_vecs, axis=1)
    print(f"  Norma palma tras normalización (debe ser ≈1): "
          f"media={palm_norms.mean():.4f}  std={palm_norms.std():.4f}")

